enum class AppLanguage(val code: String, val displayName: String, val nativeName: String) {
    VIETNAMESE("vi", "Tiếng Việt", "Tiếng Việt"),
    ENGLISH("en", "Tiếng Anh", "English"),
    FRENCH("fr", "Tiếng Pháp", "Français"),
    SPANISH("es", "Tiếng Tây Ban Nha", "Español"),
    CHINESE("zh", "Tiếng Trung", "中文"),
    KOREAN("ko", "Tiếng Hàn", "한국어");

    companion object {
        fun fromCode(code: String): AppLanguage {
            return entries.firstOrNull { it.code.equals(code, ignoreCase = true) } ?: VIETNAMESE
        }
    }
}


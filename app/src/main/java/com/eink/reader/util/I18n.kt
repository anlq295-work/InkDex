    CHINESE("zh", "Tiếng Trung", "中文"),
    KOREAN("ko", "Tiếng Hàn", "한국어");

    companion object {
        fun fromCode(code: String): AppLanguage {
            return entries.firstOrNull { it.code.equals(code, ignoreCase = true) } ?: VIETNAMESE
